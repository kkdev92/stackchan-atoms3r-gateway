    [Fact]
    public void 通常の日本語本文は保留しない()
    {
        // Return text that does not begin with JSON to the stream immediately.
        const string plain = "はい、嬉しい顔にしますね。";

        var buffer = new StringBuilder(plain);
        var (calls, text) = ToolCallText.DrainBuffer(buffer, flush: false, KnownTools);

