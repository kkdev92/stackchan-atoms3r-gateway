        buffer.Length.ShouldBe(0);
    }

    [Fact]
    public void 複数チャンクにまたがる_タグなし_JSON_を組み立てる()
    {
        const string bare =
            """{"name": "nod_stackchan", "arguments": {}}""";

        var buffer = new StringBuilder();
        var calls = new List<FunctionCallContent>();
        var text = new StringBuilder();

        foreach (var c in bare)
        {
            buffer.Append(c);

            var (chunkCalls, chunkText) = ToolCallText.DrainBuffer(
                buffer, flush: false, KnownTools);

            calls.AddRange(chunkCalls);
            text.Append(chunkText);
        }

        var (lastCalls, lastText) = ToolCallText.DrainBuffer(
            buffer, flush: true, KnownTools);

        calls.AddRange(lastCalls);
        text.Append(lastText);

        calls.Count.ShouldBe(1);
        calls[0].Name.ShouldBe("nod_stackchan");

        // Do not include incomplete JSON in text sent to the device.
        text.ToString().ShouldBeEmpty();
    }

    [Fact]
    public void JSON_で始まる本文でも_ツール呼び出しでなければ返す()
    {
        // Treat JSON that does not name a declared tool as regular response text.
        const string plain = """{"天気": "晴れ"} と表示されています。""";

        var buffer = new StringBuilder(plain);
        var (calls, text) = ToolCallText.DrainBuffer(buffer, flush: true, KnownTools);

        calls.ShouldBeEmpty();
        text.ShouldBe(plain);
    }

    [Fact]
    public void Phi4_のタグと配列からツール呼び出しを取り出す()
    {
        // Phi-4 places an array inside <|tool_call|> and returns arguments as parameters.
        var buffer = new StringBuilder(
            """<|tool_call|>[{"name": "get_current_time", "parameters": {}}]<|/tool_call|>""");

        var (calls, text) = ToolCallText.DrainBuffer(buffer, flush: true, KnownTools);

        calls.Count.ShouldBe(1);
        calls[0].Name.ShouldBe("get_current_time");

        // Do not include tool-call JSON in text sent to the device.
        text.Trim().ShouldBeEmpty();
    }

    [Fact]
    public void Phi4_の_parameters_をツール引数として解析する()
    {
        var buffer = new StringBuilder(
            """
            <|tool_call|>[{"name": "set_stackchan_expression", "parameters": {"expression": "happy"}}]<|/tool_call|>
            """);

        var (calls, _) = ToolCallText.DrainBuffer(buffer, flush: true, KnownTools);

        calls.Count.ShouldBe(1);
        calls[0].Arguments.ShouldNotBeNull();
        calls[0].Arguments!["expression"].ShouldBe("happy");
    }

    [Fact]
    public void 表情マーカーを_JSON_配列として扱わない()
    {
        // Array support must not remove response markers such as [happy].
        const string spoken = "[happy]おはようございます。[neutral]よい天気です。";

        var buffer = new StringBuilder(spoken);
        var (calls, text) = ToolCallText.DrainBuffer(buffer, flush: true, KnownTools);

        calls.ShouldBeEmpty();
        text.ShouldBe(spoken);
    }

    [Fact]
    public async Task 構造化呼び出しと本文の呼び出しが重複しても_ツールは_1_度だけ実行する()
    {
        // When the same call appears in tool_calls and text, keep the structured call and remove the duplicate.
        using var fake = new FakeChatClient();
        fake.Rounds.Add(
        [
            new TextContent("""<|tool_call|>[{"name": "get_"""),
            new TextContent("""current_time", "parameters": {}}]<|/tool_call|>"""),
            new FunctionCallContent("server-id", "get_current_time", new Dictionary<string, object?>()),
        ]);

        using var client = new TextToolCallChatClient(fake);

        var options = new ChatOptions
        {
            Tools = [AIFunctionFactory.Create(() => "12:00", "get_current_time")],
        };

        var calls = new List<FunctionCallContent>();
        var spoken = new StringBuilder();

        await foreach (var update in client.GetStreamingResponseAsync(
            [new ChatMessage(ChatRole.User, "今何時ですか")],
            options,
            TestContext.Current.CancellationToken))
        {
            foreach (var content in update.Contents)
            {
                if (content is FunctionCallContent call)
                {
                    calls.Add(call);
                }
                else if (content is TextContent text)
                {
                    spoken.Append(text.Text);
                }
            }
        }

        calls.Count.ShouldBe(1);
        calls[0].Name.ShouldBe("get_current_time");
        spoken.ToString().ShouldNotContain("tool_call");
    }
